def route_section_map() -> dict[str, str]:
    result: dict[str, str] = {}
    for section_id, routes in SECTION_ROUTES.items():
        for route in routes:
            if route in result:
                raise ValueError(f"Route {route} is assigned twice")
            result[route] = section_id
    return result


def subsection_id(section_id: str, route: str, position: int) -> str:
    return ROUTE_SUBSECTION_IDS.get(route, f"{section_id}-R{position:02d}")


def build_group_product_map() -> dict[str, list[str]]:
    mapping: dict[str, list[str]] = defaultdict(list)
    for product_section in PRODUCT_SECTIONS:
        for group_id in product_section["groups"]:
            mapping[group_id].append(product_section["id"])
    for group_id, section_ids in GROUP_PRODUCT_SUBSECTIONS.items():
        mapping[group_id].extend(section_ids)
    return {group_id: unique(section_ids) for group_id, section_ids in mapping.items()}


def build_group_task_map() -> dict[str, list[str]]:
    mapping: dict[str, list[str]] = defaultdict(list)
    for implementation_phase in IMPLEMENTATION_PHASES:
        for item in implementation_phase["tasks"]:
            for group_id in item["source_groups"]:
                mapping[group_id].append(item["id"])
    return {group_id: unique(task_ids) for group_id, task_ids in mapping.items()}


def validate_master_inputs(
    target_routes: list[dict[str, Any]], audit: dict[str, Any]
) -> tuple[dict[str, str], dict[str, list[str]], dict[str, list[str]]]:
    errors: list[str] = []
    product_ids = [item["id"] for item in PRODUCT_SECTIONS]
    if len(product_ids) != len(set(product_ids)):
        errors.append("Product section IDs are not unique")
    if product_ids != [f"P{index:02d}" for index in range(31)]:
        errors.append("Product sections must be exactly P00..P30")

    route_mapping = route_section_map()
    target_paths = [item["path"] for item in target_routes]
    if len(target_paths) != len(set(target_paths)):
        errors.append("Target route paths are not unique")
    if set(target_paths) != set(route_mapping):
        errors.append(
            f"Target route mismatch: missing={sorted(set(route_mapping) - set(target_paths))}, "
            f"extra={sorted(set(target_paths) - set(route_mapping))}"
        )

    image_units = audit.get("image_text_units", [])
    if [item.get("image") for item in image_units] != list(range(1, 30)):
        errors.append("Image-text source units must be ordered exactly 1..29")
    required_image_fields = {
        "paragraph",
        "source_context_paragraphs",
        "previous_paragraph",
        "previous_text",
        "next_paragraph",
        "next_text",
        "semantic_anchor_paragraphs",
        "semantic_anchor_texts",
        "boundary_context_paragraphs",
        "context_relationship",
        "combined_contextual_interpretation",
    }
    for item in image_units:
        missing = sorted(required_image_fields - set(item))
        if missing:
            errors.append(f"Image {item.get('image')} lacks fields {missing}")
        if not item.get("semantic_anchor_paragraphs"):
            errors.append(f"Image {item.get('image')} has no semantic anchors")

    phase_ids = [item["id"] for item in IMPLEMENTATION_PHASES]
    if phase_ids != list(EXPECTED_TASKS):
        errors.append(f"Implementation phases mismatch: {phase_ids}")
    required_task_fields = {
        "id",
        "title",
        "objective",
        "source_groups",
        "routes",
        "preserve",
        "candidate",
        "modules",
        "protocol",
        "ui",
        "states",
        "automated_tests",
        "manual_acceptance",
        "rollback",
        "visible_result",
    }
    all_task_ids: list[str] = []
    for implementation_phase in IMPLEMENTATION_PHASES:
        actual = [item["id"] for item in implementation_phase["tasks"]]
        if actual != EXPECTED_TASKS[implementation_phase["id"]]:
            errors.append(
                f"Task IDs for {implementation_phase['id']} mismatch: {actual}"
            )
        for item in implementation_phase["tasks"]:
            all_task_ids.append(item["id"])
            missing = sorted(required_task_fields - set(item))
            if missing:
                errors.append(f"Task {item.get('id')} lacks fields {missing}")
            for field in required_task_fields - {"routes"}:
                value = item.get(field)
                if value in (None, "", []):
                    errors.append(f"Task {item.get('id')} has empty {field}")
    if len(all_task_ids) != len(set(all_task_ids)):
        errors.append("Implementation task IDs are not unique")

    groups = {item["id"] for item in audit.get("groups", [])}
    atomic_groups = {item["group_id"] for item in audit.get("atomic_requirements", [])}
    product_group_map = build_group_product_map()
    task_group_map = build_group_task_map()
    if groups != atomic_groups:
        errors.append("Audit groups and atomic requirement groups differ")
    required_atomic_fields = {
        "atomic_requirement_id",
        "correct_product_interpretation",
        "page_layout_and_interaction",
        "product_section_ids",
        "primary_product_section_id",
        "implementation_task_ids",
        "primary_implementation_task_id",
        "product_realization_contract",
        "implementation_realization_contract",
        "automatic_validation",
        "manual_acceptance",
    }
    for atom in audit.get("atomic_requirements", []):
        missing = sorted(required_atomic_fields - set(atom))
        if missing:
            errors.append(
                f"Atomic requirement {atom.get('atomic_requirement_id')} lacks fields {missing}"
            )
        for field in required_atomic_fields:
            if atom.get(field) in (None, "", []):
                errors.append(
                    f"Atomic requirement {atom.get('atomic_requirement_id')} has empty {field}"
                )
    missing_product = sorted(groups - set(product_group_map))
    missing_tasks = sorted(groups - set(task_group_map))
    if missing_product:
        errors.append(f"Groups missing product sections: {missing_product}")
    if missing_tasks:
        errors.append(f"Groups missing implementation tasks: {missing_tasks}")

    valid_product_ids = set(product_ids)
    valid_product_ids.update(ROUTE_SUBSECTION_IDS.values())
    for subsections in EXTRA_PRODUCT_SUBSECTIONS.values():
        valid_product_ids.update(item[0] for item in subsections)
    for group_id, section_ids in product_group_map.items():
        invalid = sorted(set(section_ids) - valid_product_ids)
        if invalid:
            errors.append(f"Group {group_id} references invalid product IDs {invalid}")

    if errors:
        raise ValueError("; ".join(errors))
    return route_mapping, product_group_map, task_group_map


def build_product_model(
    target_routes: list[dict[str, Any]],
    audit: dict[str, Any],
    route_mapping: dict[str, str],
    product_group_map: dict[str, list[str]],
) -> dict[str, Any]:
    target_by_path = {item["path"]: dict(item) for item in target_routes}
    image_by_number = {
        int(item["image"]): dict(item) for item in audit["image_text_units"]
    }
    extra_by_id = {
        item[0]: {"id": item[0], "title": item[1], "contracts": item[2]}
        for values in EXTRA_PRODUCT_SUBSECTIONS.values()
        for item in values
    }
    atomic_contracts = [
        build_atomic_contract(atom) for atom in audit["atomic_requirements"]
    ]
    route_records: list[dict[str, Any]] = []
    section_records: list[dict[str, Any]] = []
    for product_section in PRODUCT_SECTIONS:
        section_record = dict(product_section)
        enriched_routes: list[dict[str, Any]] = []
        for position, path in enumerate(product_section["routes"], start=1):
            route = dict(target_by_path[path])
            route["section_id"] = product_section["id"]
            route["subsection_id"] = subsection_id(
                product_section["id"], path, position
            )
            if route["subsection_id"] in extra_by_id:
                route["additional_contracts"] = extra_by_id[route["subsection_id"]][
                    "contracts"
                ]
            else:
                route["additional_contracts"] = []
            route["atomic_contracts"] = [
                contract
                for contract in atomic_contracts
                if route["subsection_id"]
                == contract["primary_product_section_id"]
            ]
            enriched_routes.append(route)
            route_records.append(route)
        section_record["route_specs"] = enriched_routes
        section_record["image_text_units"] = [
            image_by_number[number] for number in product_section["images"]
        ]
        route_subsection_ids = {
            item["subsection_id"] for item in enriched_routes
        }
        standalone_subsections = []
        for subsection in EXTRA_PRODUCT_SUBSECTIONS.get(product_section["id"], []):
            if subsection[0] in route_subsection_ids:
                continue
            standalone_subsections.append(
                {
                    "id": subsection[0],
                    "title": subsection[1],
                    "contracts": subsection[2],
                    "atomic_contracts": [
                        contract
                        for contract in atomic_contracts
                        if subsection[0]
                        == contract["primary_product_section_id"]
                    ],
                }
            )
        section_record["standalone_subsections"] = standalone_subsections
        section_scope_ids = {
            product_section["id"],
            *(item["subsection_id"] for item in enriched_routes),
            *(item["id"] for item in standalone_subsections),
        }
        section_record["atomic_contracts"] = [
            contract
            for contract in atomic_contracts
            if contract["primary_product_section_id"] in section_scope_ids
        ]
        section_records.append(section_record)
    return {
        "schema_version": "3.0",
        "status": "TARGET_PRODUCT_SPEC / IMPLEMENTATION_PENDING",
        "authority": "SPEC-REWRITE-ATOMIC-COVERAGE",
        "product_section_count": len(section_records),
        "target_route_count": len(route_records),
        "word_paragraph_count": audit["paragraph_count"],
        "image_text_unit_count": len(audit["image_text_units"]),
        "atomic_requirement_count": audit["atomic_requirement_count"],
        "sections": section_records,
        "routes": route_records,
        "group_product_section_map": product_group_map,
        "image_text_units": audit["image_text_units"],
        "atomic_contracts": atomic_contracts,
    }


def build_implementation_model(
    audit: dict[str, Any], task_group_map: dict[str, list[str]]
) -> dict[str, Any]:
    groups = {item["id"]: item for item in audit["groups"]}
    atoms_by_group: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for atom in audit["atomic_requirements"]:
        atoms_by_group[atom["group_id"]].append(atom)
    images = {
        int(item["image"]): item for item in audit["image_text_units"]
    }
    all_atomic_contracts = [
        build_atomic_contract(atom) for atom in audit["atomic_requirements"]
    ]
    phase_records: list[dict[str, Any]] = []
    task_records: list[dict[str, Any]] = []
    for implementation_phase in IMPLEMENTATION_PHASES:
        phase_record = dict(implementation_phase)
        enriched_tasks: list[dict[str, Any]] = []
        for item in implementation_phase["tasks"]:
            task_record = dict(item)
            source_atoms = [
                atom
                for atom in audit["atomic_requirements"]
                if atom["primary_implementation_task_id"] == item["id"]
            ]
            source_group_ids = unique(
                list(item["source_groups"])
                + [atom["group_id"] for atom in source_atoms]
            )
            task_record["source_groups"] = source_group_ids
            source_group_records = [groups[group_id] for group_id in source_group_ids]
            related_atoms = [
                atom
                for group_id in source_group_ids
                for atom in atoms_by_group[group_id]
            ]
            source_paragraphs = sorted(
                {
                    paragraph
                    for group in source_group_records
                    for paragraph in group["paragraphs"]
                }
            )
            source_images = sorted(
                {
                    number
                    for group in source_group_records
                    for number in group["images"]
                }
            )
            task_record["source_word_paragraphs"] = source_paragraphs
            task_record["source_images"] = source_images
            task_record["source_image_text_units"] = [
                images[number] for number in source_images
            ]
            task_record["source_group_contracts"] = [
                {
                    "group_id": group["id"],
                    "group_title": group["title"],
                    "layout_and_interaction": group["layout_and_interaction"],
                    "target_routes": group["routes"],
                    "manual_acceptance": group["manual_acceptance"],
                }
                for group in source_group_records
            ]
            task_record["atomic_contracts"] = [
                build_atomic_contract(atom) for atom in source_atoms
            ]
            task_record["related_atomic_requirement_ids"] = [
                atom["atomic_requirement_id"] for atom in related_atoms
            ]
            task_record["atomic_requirement_ids"] = [
                contract["atomic_requirement_id"]
                for contract in task_record["atomic_contracts"]
            ]
            task_record["full_state_contract"] = FULL_STATE_CONTRACT
            enriched_tasks.append(task_record)
            task_records.append(task_record)
        phase_record["tasks"] = enriched_tasks
        phase_records.append(phase_record)
    return {
        "schema_version": "3.1",
        "status": "IMPLEMENTATION_PLAN / CODE_NOT_STARTED_BY_THIS_GOAL",
        "authority": "SPEC-REWRITE-ATOMIC-COVERAGE",
        "phase_count": len(phase_records),
        "task_count": len(task_records),
        "atomic_requirement_count": audit["atomic_requirement_count"],
        "f1_design_contract": f1_design_inheritance_contract(),
        "phases": phase_records,
        "tasks": task_records,
        "group_implementation_task_map": task_group_map,
        "atomic_contracts": all_atomic_contracts,
    }


