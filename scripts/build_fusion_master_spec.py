def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workspace", type=Path, default=Path("."))
    parser.add_argument(
        "--product-output",
        type=Path,
        default=Path("outputs/原系统融合重构执行/09_EduMatrix最终产品方案.md"),
    )
    parser.add_argument(
        "--implementation-output",
        type=Path,
        default=Path("outputs/原系统融合重构执行/10_原版融合重构详细实施方案.md"),
    )
    args = parser.parse_args()
    root = args.workspace.resolve()
    target_routes = json.loads(
        (
            root
            / "outputs"
            / "原系统融合重构执行"
            / "evidence"
            / "target_product_spec"
            / "target_product_route_spec.json"
        ).read_text(encoding="utf-8")
    )
    audit = json.loads(
        (
            root
            / "outputs"
            / "原系统融合重构执行"
            / "13_改进想法逐句逐图实质落实审计.json"
        ).read_text(encoding="utf-8")
    )
    route_mapping, product_group_map, task_group_map = validate_master_inputs(
        target_routes, audit
    )
    product_model = build_product_model(
        target_routes, audit, route_mapping, product_group_map
    )
    implementation_model = build_implementation_model(audit, task_group_map)

    product_output = (
        args.product_output
        if args.product_output.is_absolute()
        else root / args.product_output
    )
    implementation_output = (
        args.implementation_output
        if args.implementation_output.is_absolute()
        else root / args.implementation_output
    )
    product_output.parent.mkdir(parents=True, exist_ok=True)
    implementation_output.parent.mkdir(parents=True, exist_ok=True)
    product_output.write_text(render_product_markdown(product_model), encoding="utf-8")
    product_output.with_suffix(".json").write_text(
        json.dumps(product_model, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    implementation_output.write_text(
        render_implementation_markdown(implementation_model), encoding="utf-8"
    )
    implementation_output.with_suffix(".json").write_text(
        json.dumps(implementation_model, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
