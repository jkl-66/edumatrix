def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--routes", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    rows = read_csv(args.routes)
    missing_specs = [row["path"] for row in rows if row["path"] not in ROUTE_SPECS]
    if missing_specs:
        raise SystemExit(
            "Missing explicit route specifications: " + ", ".join(missing_specs)
        )
    current_paths = {row["path"] for row in rows}
    destination_paths = set(TARGET_DESTINATIONS)
    if current_paths != destination_paths:
        missing_destinations = sorted(current_paths - destination_paths)
        stale_destinations = sorted(destination_paths - current_paths)
        raise SystemExit(
            "Target destination mapping mismatch; missing="
            + ", ".join(missing_destinations)
            + "; stale="
            + ", ".join(stale_destinations)
        )
    for row in rows:
        spec = ROUTE_SPECS[row["path"]]
        row.update(spec)
        row["target_destination"] = TARGET_DESTINATIONS[row["path"]]
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "route_product_spec.json").write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    (args.output / "route_product_spec.md").write_text(render_markdown(rows), encoding="utf-8")
    print(json.dumps({"routes": len(rows), "explicit_specs": len(rows)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
