def generic_spec(route: str, page: dict[str, str]) -> dict[str, str]:
    path = route.lower()
    if path.startswith("/teacher") or path in {"/course-governance", "/teaching-analytics"}:
        role = "教师"
        value = "用少量班级、课程和学习证据完成教学维护或干预"
        primary = "打开需要处理的课程/学生"
    elif path.startswith("/admin") or path in {"/content-review", "/model-operations"}:
        role = "管理员"
        value = "维护账号、模型、内容质量和系统可用性"
        primary = "处理当前待办"
    elif "judge" in path or "showcase" in path or "advanced" in path or "internal" in path:
        role = "评委/开发者"
        value = "查看比赛闭环证据，不进入普通用户学习主线"
        primary = "打开证据或演示旅程"
    else:
        role = "学生/教师按权限"
        value = "在学习空间内完成对应资源、测评或辅助任务"
        primary = "开始当前任务"
    return {
        "role": role,
        "value": value,
        "primary_action": primary,
        "input": "课程上下文、当前用户、路由参数和对应资源/任务",
        "output": "页面结果、可恢复深链和统一学习事件（若属于学习动作）",
        "states": "加载、空、处理中、失败可重试/回退、完成",
        "events": "按任务类型写入资源、测评、复习、画像/路径或后台审计；内部页不得污染学生事件",
        "baseline": "原版无直接对应页面或对应入口已在上方明确",
        "candidate": f"当前路由组件 `{page.get('view') or page.get('component')}` 与对应 API/后端模块",
        "disposition": "按路由迁移矩阵处置",
    }


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


