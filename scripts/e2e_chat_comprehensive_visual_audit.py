def shot(page: Page, report: dict, scenario_id: str, size: str, suffix: str = "answer") -> str:
    page.wait_for_timeout(500)
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{scenario_id}-{suffix}-{size}.png"
    page.screenshot(path=str(path), full_page=True)
    report["screenshots"].append({
        "scenario": scenario_id,
        "name": path.name,
        "path": str(path),
        "viewport": [page.viewport_size["width"], page.viewport_size["height"]],
        "url": page.url,
    })
    return str(path)


def wait_new_conversation(page: Page) -> None:
    page.get_by_role("button", name="新建对话", exact=True).click()
    # The empty-state illustration is intentionally allowed to be replaced by
    # another loading/empty variant at narrow widths.  The stable contract is
    # that the new conversation has no message rows and the composer is ready.
    page.wait_for_function(
        """() => document.querySelectorAll('.message-row').length === 0
                    && !!document.querySelector('[data-testid="chat-composer"]')""",
        timeout=30_000,
    )


def send_and_wait(page: Page, question: str) -> tuple[str, str]:
    composer = page.get_by_label("输入问题")
    composer.fill(question)
    # Vue's v-model update is asynchronous after a conversation switch.  Wait
    # for the actual textarea value and the enabled send control, otherwise a
    # narrow viewport can capture the first click while the draft is still
    # being committed.
    page.wait_for_function(
        """(expected) => {
          const input = document.querySelector('textarea.composer-input')
          const button = document.querySelector('.send-button')
          return input?.value === expected && button && !button.disabled
        }""",
        arg=question,
        timeout=15_000,
    )
    page.locator(".send-button").click()
    user_row = page.locator(".message-row--user").filter(has_text=question).last
    user_row.wait_for(state="visible", timeout=30_000)
    assistant = user_row.locator("xpath=following-sibling::article[contains(@class,'message-row--assistant')][1]")
    assistant.wait_for(state="visible", timeout=45_000)
    assistant_id = assistant.get_attribute("data-message-id")
    page.wait_for_function(
        """(messageId) => {
          const row = document.querySelector(`[data-message-id="${messageId}"]`)
          const label = row?.querySelector('.assistant-label')?.innerText || ''
          const answer = row?.querySelector('.assistant-answer')?.innerText || ''
          return label.includes('回答完成') && answer.trim().length > 0
        }""",
        arg=assistant_id,
        timeout=75_000,
    )
    return assistant.locator(".assistant-answer").inner_text().strip(), str(assistant_id)


def check_content(content: str, scenario: dict) -> dict:
    missing = [item for item in scenario.get("must", []) if item.lower() not in content.lower()]
    # The rendered assistant surface should expose headings/lists as visual
    # structure, never as raw Markdown control characters.  Check the visible
    # text rather than the stored Markdown payload so this catches regressions
    # in the browser renderer without constraining the model's source format.
    forbidden_markdown = ("## ", "### ", "```")
    forbidden = [item for item in (*scenario.get("must_not", []), *forbidden_markdown) if item.lower() in content.lower()]
    lower = len(content) < int(scenario.get("min_chars", 0))
    upper = bool(scenario.get("max_chars")) and len(content) > int(scenario["max_chars"])
    return {
        "passed": not missing and not forbidden and not lower and not upper,
        "chars": len(content),
        "missing": missing,
        "forbidden": forbidden,
        "below_min": lower,
        "above_max": upper,
    }


def run_size(page: Page, report: dict, size: str) -> dict:
    page.goto(f"{BASE_URL}/chat?course_id={COURSE_ID}", wait_until="domcontentloaded", timeout=60_000)
    page.get_by_test_id("focused-chat-workspace").wait_for(state="visible", timeout=45_000)
    page.get_by_test_id("chat-composer").wait_for(state="visible", timeout=30_000)
    page.wait_for_timeout(900)
    # Create one clean conversation per scenario to prevent old answers from
    # affecting visual evidence.  The conversation itself is created by the
    # visible SPA button, not by a test-only API shortcut.
    results = {}
    for scenario in SCENARIOS:
        wait_new_conversation(page)
        question = scenario["question"]
        content, message_id = send_and_wait(page, question)
        check = check_content(content, scenario)
        failure_ui = page.get_by_text("回答暂时中断", exact=False).count() > 0 or page.get_by_text("回答失败", exact=False).count() > 0
        check["failure_ui"] = failure_ui
        path = shot(page, report, scenario["id"], size)
        results[scenario["id"]] = {
            "question": question,
            "message_id": message_id,
            "content": content,
            "content_check": check,
            "screenshot": path,
            "status_text": page.locator(".answer-status").inner_text().strip(),
        }
    # A dedicated two-turn context-conflict check demonstrates that a short
    # follow-up is not copied verbatim from the first answer.
    wait_new_conversation(page)
    first = "请解释混合检索中关键词召回和向量召回的分工。"
    first_content, _ = send_and_wait(page, first)
    follow = "现在换一个问题：二分查找在闭区间中为什么必须写 right = mid - 1？"
    follow_content, _ = send_and_wait(page, follow)
    conflict_check = {
        "passed": (
            len(follow_content) >= 450
            and "right = mid - 1" in follow_content
            and "混合检索把两路互补" not in follow_content
            and follow_content != first_content
        ),
        "first_chars": len(first_content),
        "follow_chars": len(follow_content),
        "follow_topic_evidence": "right = mid - 1" in follow_content,
        "unrelated_topic_absent": "混合检索把两路互补" not in follow_content,
        "answers_distinct": follow_content != first_content,
    }
    results["context-conflict-follow-up"] = {
        "question": follow,
        "content": follow_content,
        "content_check": conflict_check,
        "screenshot": shot(page, report, "context-conflict-follow-up", size, "answer"),
        "status_text": page.locator(".answer-status").inner_text().strip(),
    }
    return results


def main() -> int:
    copy_isolated_db()
    username, public_id, _ = db_identity()
    formal_db = ROOT / "edumatrix.db"
    report: dict = {
        "schema_version": "chat-comprehensive-visual-audit.v1",
        "result": "failed",
        "service": BASE_URL,
        "database": str(DB_PATH),
        "username": username,
        "public_id": public_id,
        "screenshots": [],
        "viewports": {},
        "http_errors": [],
        "failed_requests": [],
        "page_errors": [],
        "console_errors": [],
        "external_requests": [],
        "formal_db_before": {"exists": formal_db.exists(), "sha256": digest(formal_db) if formal_db.exists() else None},
    }
    process = None
    try:
        process = subprocess.Popen(
            [sys.executable, "run.py"], cwd=ROOT, env=env_for_run(),
            stdout=(EVIDENCE / "chat_comprehensive_backend.log").open("w", encoding="utf-8"),
            stderr=subprocess.STDOUT,
        )
        wait_port(True)
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(channel="chrome", headless=True)
            for width, height, label in ((1440, 900, "1440x900"), (1366, 768, "1366x768")):
                context = browser.new_context(viewport={"width": width, "height": height}, locale="zh-CN")
                page = context.new_page()
                diagnostics(page, report)
                token = login(page, username)
                report["viewports"][label] = run_size(page, report, label)
                context.close()
            browser.close()
        with sqlite3.connect(DB_PATH) as db:
            report["database_integrity"] = {
                "integrity": db.execute("PRAGMA integrity_check").fetchone()[0],
                "foreign_key_violations": len(db.execute("PRAGMA foreign_key_check").fetchall()),
                "chat_messages": db.execute("SELECT COUNT(*) FROM chat_messages WHERE owner_public_id=?", (public_id,)).fetchone()[0],
            }
        report["formal_db_after"] = {"exists": formal_db.exists(), "sha256": digest(formal_db) if formal_db.exists() else None}
        all_checks = [
            item["content_check"]
            for viewport in report["viewports"].values()
            for item in viewport.values()
        ]
        report["checks"] = {
            "all_content_checks_passed": all(check.get("passed") and not check.get("failure_ui") for check in all_checks),
            "no_unexpected_browser_errors": not (report["http_errors"] or report["failed_requests"] or report["page_errors"] or report["console_errors"] or report["external_requests"]),
            "database_integrity_ok": report["database_integrity"]["integrity"] == "ok" and report["database_integrity"]["foreign_key_violations"] == 0,
            "formal_db_unchanged": report["formal_db_after"] == report["formal_db_before"],
        }
        if all(report["checks"].values()):
            report["result"] = "passed"
        else:
            raise AssertionError(report["checks"])
    except Exception as exc:
        report["error"] = f"{type(exc).__name__}: {exc}"
        report["traceback"] = traceback.format_exc()
    finally:
        if process is not None and process.poll() is None:
            subprocess.run(["taskkill", "/PID", str(process.pid), "/T", "/F"], capture_output=True, text=True, timeout=20)
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                pass
        report["process_cleanup"] = process is None or process.poll() is not None
        report["finished_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
        (EVIDENCE / "chat_comprehensive_visual_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"result": report["result"], "screenshots": len(report["screenshots"]), "error": report.get("error")}, ensure_ascii=False))
    return 0 if report["result"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
