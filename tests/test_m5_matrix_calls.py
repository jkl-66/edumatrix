import asyncio

import pytest
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

from app.database import Base, DBModelCall
from instruct_rag import AsyncInstructRAGGenerator
from models import GraphContext, StudentProfile


class Backend:
    model = "matrix-test-model"

    def __init__(self, *, fail_role=""):
        self.fail_role = fail_role

    async def generate(self, system_prompt, user_prompt, *, role):
        if role == self.fail_role:
            raise RuntimeError("agent provider unavailable")
        return f"generated by {role}"


def _fixture(*, fail_role=""):
    engine = create_engine("sqlite:///:memory:")
    Base.metadata.create_all(engine)
    session = sessionmaker(bind=engine)()

    async def database_runner(operation, *args):
        return operation(session, *args)

    generator = AsyncInstructRAGGenerator(Backend(fail_role=fail_role))
    context = {
        "trace_id": "m5-matrix-shared-trace",
        "owner_public_id": "matrix-owner",
        "course_id": "matrix-course",
        "database_runner": database_runner,
    }
    arguments = {
        "query": "private matrix query",
        "graph_context": GraphContext("逻辑回归", ("逻辑回归",), (), ()),
        "evidence": (),
        "profile": StudentProfile(student_id="matrix-owner"),
        "model_call_context": context,
    }
    return session, generator, arguments


def test_matrix_agents_share_trace_but_keep_individual_calls():
    session, generator, arguments = _fixture()

    async def exercise():
        await generator.generate(role="理论教授", resource_type="专业讲义", **arguments)
        await generator.generate(role="逻辑画师", resource_type="知识图谱", **arguments)

    asyncio.run(exercise())
    rows = session.query(DBModelCall).order_by(DBModelCall.created_at).all()
    assert len(rows) == 2
    assert {row.trace_id for row in rows} == {"m5-matrix-shared-trace"}
    assert len({row.id for row in rows}) == 2
    assert {row.input_summary["agent_role"] for row in rows} == {"理论教授", "逻辑画师"}
    assert all(row.status == "completed" for row in rows)
    assert all(row.owner_public_id == "matrix-owner" for row in rows)
    assert all("private matrix query" not in str(row.input_summary) for row in rows)


def test_matrix_agent_failure_is_terminal_before_factory_fallback():
    session, generator, arguments = _fixture(fail_role="极客助教")
    with pytest.raises(RuntimeError, match="provider unavailable"):
        asyncio.run(generator.generate(
            role="极客助教", resource_type="代码实操案例", **arguments,
        ))
    row = session.query(DBModelCall).one()
    assert row.trace_id == "m5-matrix-shared-trace"
    assert (row.status, row.error_code) == ("failed", "agent_provider_failed")
